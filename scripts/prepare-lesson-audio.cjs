// Produce an exact recording plan from authored English. Never synthesizes or invents speech.
const fs = require('node:fs');
const path = require('node:path');
const crypto = require('node:crypto');
const root = path.resolve(__dirname, '..');
const lessons = JSON.parse(fs.readFileSync(path.join(root, 'src/data/b1Packet.json'), 'utf8'));
const texts = new Set();
function card(item) {
 if (item.audio) texts.add(item.audio);
 for (const text of item.examples || []) texts.add(text);
 for (const turn of item.turns || []) { texts.add(turn.audio); if (turn.reply) texts.add(turn.reply); }
 if (item.review) card(item.review);
}
for (const lesson of lessons) { lesson.cards.forEach(card); lesson.vocabulary.forEach(v => { texts.add(v.word); texts.add(v.example); }); }
const plan = [...texts].filter(Boolean).map(text => ({ id: crypto.createHash('sha256').update(text).digest('hex').slice(0, 16), text, locale: 'en-GB' }));
const manifestPath = path.join(root, 'assets/audio/lessons/recording-plan.json');
fs.writeFileSync(manifestPath, JSON.stringify(plan, null, 2) + '\n');
const available = plan.flatMap(item => ['m4a', 'mp3', 'wav'].filter(ext => fs.existsSync(path.join(root, `assets/audio/lessons/${item.id}.${ext}`))).map(ext => ({ ...item, file: `${item.id}.${ext}` })));
if (process.argv.includes('--bind')) {
 const duplicates = available.filter((item, i) => available.findIndex(other => item.id === other.id) !== i);
 if (duplicates.length) throw Error('Keep one reviewed audio file per script before binding.');
 const head = `/** Reviewed bundled recordings; generated by scripts/prepare-lesson-audio.cjs --bind. */\nexport interface PreparedLessonAudio { text: string; locale: 'en-GB'; asset: number }\nexport const preparedLessonAudio: PreparedLessonAudio[] = [\n`;
 const entries = available.map(item => `  { text: ${JSON.stringify(item.text)}, locale: 'en-GB', asset: require('../../assets/audio/lessons/${item.file}') },`).join('\n');
 const lookup = `\n];\nexport function preparedAudioSource(text: string): number | undefined {\n  const key = (value: string) => value.replace(/[‘’]/g, "'").replace(/\\s+/g, ' ').trim().toLowerCase();\n  return preparedLessonAudio.find(item => item.locale === 'en-GB' && key(item.text) === key(text))?.asset;\n}\n`;
 fs.writeFileSync(path.join(root, 'src/data/preparedLessonAudio.ts'), head + entries + lookup);
}
console.log(`${plan.length} exact English scripts; ${available.length} bundled files; ${plan.length - available.length} recordings missing.`);
