const assert = require('node:assert/strict'), fs = require('node:fs'), Module = require('node:module'), ts = require('typescript'), React = require('react');
const original = Module._load;
let options, available = true, starts = 0, stopped = 0;
const speech = { phase: 'idle', available: true, partial: '', message: '', busy: false, level: 0, draft: null, needsModel: false, needsNetwork: false, start: () => starts++, stop: () => stopped++, cancel() {} };
const player = { pause() {}, replace() {}, seekTo: async () => {}, play() {} };
const native = { View: 'View', Text: 'Text', Pressable: 'Pressable', TextInput: 'TextInput', ScrollView: 'ScrollView', StyleSheet: { create: x => x, flatten: x => x } };
Module._load = function(name, parent, main) {
  if (name === 'react') return React;
  if (name === 'react-native') return native;
  if (name === 'expo-audio') return { useAudioPlayer: () => player, useAudioPlayerStatus: () => ({ playing: false }) };
  if (name.endsWith('/hooks/useLessonSpeech')) return { useLessonSpeech: opts => { options = opts; return { ...speech, available }; } };
  if (name === './VoicePracticeRecorder') return { __esModule: true, default: 'Recorder' };
  if (name === './ParticleWave') return { __esModule: true, default: 'Wave' };
  if (name === './LessonSurface') return { LessonIcon: 'Icon', LessonButton: 'Button', ink: {} };
  return original.call(this, name, parent, main);
};
for (const ext of ['.ts', '.tsx']) require.extensions[ext] = (m, f) => m._compile(ts.transpileModule(fs.readFileSync(f, 'utf8'), { compilerOptions: { module: ts.ModuleKind.CommonJS, jsx: ts.JsxEmit.ReactJSX, target: ts.ScriptTarget.ES2022, esModuleInterop: true } }).outputText, f);
globalThis.IS_REACT_ACT_ENVIRONMENT = true;
